package context

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/novr/kusabi/internal/manifest"
)

// Builder assembles an AI context document from the manifest.
type Builder struct {
	Manifest    *manifest.Manifest
	RootDir     string
	IncludeTree bool
}

type JSONOutput struct {
	GeneratedAt  time.Time  `json:"generated_at"`
	Meta         JSONMeta   `json:"meta"`
	Repositories []JSONRepo `json:"repositories"`
}

type JSONMeta struct {
	Name               string           `json:"name"`
	Description        string           `json:"description,omitempty"`
	AgentsContent      string           `json:"agents_content,omitempty"`
	ParentContextFiles []JSONParentFile `json:"parent_context_files,omitempty"`
}

type JSONContextFile struct {
	Path    string `json:"path"`
	Content string `json:"content"`
}

// JSONParentFile is one context.paths entry. Missing is set when the path cannot be read.
type JSONParentFile struct {
	Path    string `json:"path"`
	Content string `json:"content,omitempty"`
	Missing bool   `json:"missing,omitempty"`
}

type JSONRepo struct {
	Name         string            `json:"name"`
	Path         string            `json:"path"`
	Role         string            `json:"role,omitempty"`
	Tags         []string          `json:"tags,omitempty"`
	ContextFiles []JSONContextFile `json:"context_files,omitempty"`
	Tree         []string          `json:"tree,omitempty"`
}

// Build returns a Markdown context document.
func (b *Builder) Build() (string, error) {
	var sb strings.Builder

	sb.WriteString("# Project Context (Generated by Kusabi)\n\n")

	agentsContent := b.readAgents()
	if agentsContent != "" {
		sb.WriteString("## Meta Architecture & Global Policy\n\n")
		sb.WriteString(agentsContent)
		sb.WriteString("\n---\n\n")
	}

	if parentFiles := b.readParentContextFiles(); len(parentFiles) > 0 {
		sb.WriteString("## Parent Context Files\n\n")
		for _, f := range parentFiles {
			if f.Missing {
				sb.WriteString(fmt.Sprintf("_(missing: %s)_\n\n", f.Path))
				continue
			}
			sb.WriteString(fmt.Sprintf("### %s\n\n%s\n\n", f.Path, f.Content))
		}
		sb.WriteString("---\n\n")
	}

	names := b.sortedNames()
	sb.WriteString("## Bound Repositories Overview\n\n")
	for _, name := range names {
		repo := b.Manifest.Repositories[name]
		sb.WriteString(fmt.Sprintf("- **%s** (`%s`)\n", name, repo.Path))
		if repo.Role != "" {
			sb.WriteString(fmt.Sprintf("  - Role: %s\n", repo.Role))
		}
		if len(repo.Tags) > 0 {
			sb.WriteString(fmt.Sprintf("  - Tags: %s\n", strings.Join(repo.Tags, ", ")))
		}
	}

	sb.WriteString("\n---\n\n")
	sb.WriteString("## Repository Contexts\n\n")

	for i, name := range names {
		repo := b.Manifest.Repositories[name]
		absPath := filepath.Join(b.RootDir, repo.Path)

		sb.WriteString(fmt.Sprintf("### %d. %s (`%s`)\n", i+1, name, repo.Path))
		if repo.Role != "" {
			sb.WriteString(fmt.Sprintf("> Role: %s\n\n", repo.Role))
		}

		files := b.readContextFiles(absPath, repo)
		if len(files) == 0 {
			sb.WriteString("_(no context files found for configured includes)_\n\n")
		} else {
			for _, f := range files {
				sb.WriteString(fmt.Sprintf("#### %s\n\n", f.Path))
				sb.WriteString(f.Content)
				sb.WriteString("\n\n")
			}
		}

		if b.IncludeTree {
			tree := b.buildTree(absPath)
			if len(tree) > 0 {
				sb.WriteString("**Directory structure:**\n```\n")
				for _, line := range tree {
					sb.WriteString(line + "\n")
				}
				sb.WriteString("```\n")
			}
		}

		sb.WriteString("\n")
	}

	return sb.String(), nil
}

// BuildJSON returns the context as structured JSON.
func (b *Builder) BuildJSON() ([]byte, error) {
	out := JSONOutput{
		GeneratedAt: time.Now().UTC(),
		Meta: JSONMeta{
			Name:               b.Manifest.Name,
			Description:        b.Manifest.Description,
			AgentsContent:      b.readAgents(),
			ParentContextFiles: b.readParentContextFiles(),
		},
	}

	for _, name := range b.sortedNames() {
		repo := b.Manifest.Repositories[name]
		absPath := filepath.Join(b.RootDir, repo.Path)
		files := b.readContextFiles(absPath, repo)

		jr := JSONRepo{
			Name: name,
			Path: repo.Path,
			Role: repo.Role,
			Tags: repo.Tags,
		}
		for _, f := range files {
			jr.ContextFiles = append(jr.ContextFiles, JSONContextFile{
				Path:    f.Path,
				Content: f.Content,
			})
		}
		if b.IncludeTree {
			jr.Tree = b.buildTree(absPath)
		}
		out.Repositories = append(out.Repositories, jr)
	}

	return json.MarshalIndent(out, "", "  ")
}

func (b *Builder) readParentContextFiles() []JSONParentFile {
	if len(b.Manifest.Context.Paths) == 0 {
		return nil
	}
	var out []JSONParentFile
	for _, p := range b.Manifest.Context.Paths {
		absPath, ok := b.resolveUnderRoot(p)
		if !ok {
			out = append(out, JSONParentFile{Path: p, Missing: true})
			continue
		}
		data, err := os.ReadFile(absPath)
		if err != nil {
			out = append(out, JSONParentFile{Path: p, Missing: true})
			continue
		}
		out = append(out, JSONParentFile{Path: p, Content: string(data)})
	}
	return out
}

// resolveUnderRoot joins rel to RootDir only when it stays inside the workspace.
// Absolute paths and ".." escapes are rejected (filepath.Join would otherwise ignore RootDir).
func (b *Builder) resolveUnderRoot(rel string) (string, bool) {
	if err := manifest.ValidateRepoPath(rel); err != nil {
		return "", false
	}
	root := filepath.Clean(b.RootDir)
	abs := filepath.Join(root, filepath.Clean(rel))
	if abs != root && !strings.HasPrefix(abs, root+string(filepath.Separator)) {
		return "", false
	}
	return abs, true
}

func (b *Builder) readAgents() string {
	if b.Manifest.Context.Agents == "" {
		return ""
	}
	path := filepath.Join(b.RootDir, b.Manifest.Context.Agents)
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	return string(data)
}

type contextFile struct {
	Path    string
	Content string
}

func (b *Builder) readContextFiles(repoPath string, repo manifest.Repository) []contextFile {
	// Per-repo includes take precedence; fall back to global, then defaults.
	includes := repo.Includes
	if len(includes) == 0 {
		includes = b.Manifest.Context.Includes
	}
	if len(includes) == 0 {
		includes = []string{"README.md", "CLAUDE.md"}
	}

	var files []contextFile
	for _, name := range includes {
		path := filepath.Join(repoPath, name)
		data, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		files = append(files, contextFile{
			Path:    name,
			Content: string(data),
		})
	}
	return files
}

func (b *Builder) buildTree(repoPath string) []string {
	var lines []string
	_ = filepath.WalkDir(repoPath, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(repoPath, path)
		if rel == "." {
			return nil
		}
		parts := strings.Split(rel, string(filepath.Separator))
		for _, p := range parts {
			if strings.HasPrefix(p, ".") || p == "node_modules" || p == "vendor" {
				if d.IsDir() {
					return filepath.SkipDir
				}
				return nil
			}
		}
		depth := len(parts) - 1
		if depth > 2 {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		indent := strings.Repeat("  ", depth)
		name := d.Name()
		if d.IsDir() {
			name += "/"
		}
		lines = append(lines, indent+name)
		if d.IsDir() && depth == 2 {
			return filepath.SkipDir
		}
		return nil
	})
	return lines
}

func (b *Builder) sortedNames() []string {
	return b.Manifest.RepositoryNames()
}
